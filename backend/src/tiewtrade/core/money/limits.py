"""ค่ากลางเรื่องความละเอียดและช่วงค่า — ประกาศไว้ที่เดียวทั้งระบบ (RQ-9)

ห้ามเขียนตัวเลขเหล่านี้ซ้ำที่อื่น ทุกที่ที่ต้องรู้ค่าต้องอ้างถึงโมดูลนี้
"""

from decimal import Decimal

#: ความละเอียดของการคำนวณ ครอบบวก ลบ คูณ ของค่าใด ๆ ที่เก็บได้โดยไม่ถูกปัด
#: ค่าที่เก็บได้ยาวสุด 38 หลัก การคูณสองค่าจึงยาวได้ถึง 76 หลัก (RQ-2)
COMPUTE_PRECISION = 80

#: จำนวนหลักทั้งหมดที่ฐานข้อมูลเก็บ — NUMERIC(38, 18) (RQ-9)
STORED_PRECISION = 38

#: จำนวนตำแหน่งทศนิยมที่ฐานข้อมูลเก็บ
STORED_SCALE = 18

#: จำนวนหลักหน้าจุดที่เหลือ — 38 - 18 = 20 หลัก
_WHOLE_DIGITS = STORED_PRECISION - STORED_SCALE

# ค่าคงที่ด้านล่างสร้างจากข้อความ เพราะ **การสร้างจากข้อความไม่ผ่าน context**
# ส่วน `**` และ `scaleb` เป็นการคำนวณที่ปัดตาม context ตอน import ซึ่งเป็นจังหวะ
# ที่ยังควบคุม context ไม่ได้ ค่าขอบจึงจะเพี้ยนตามสภาพแวดล้อมที่บังเอิญ import อยู่

#: ค่าสัมบูรณ์ต้องน้อยกว่าค่านี้ (RQ-22)
MAX_ABS = Decimal(f"1E+{_WHOLE_DIGITS}")

#: หน่วยที่เล็กที่สุดที่เก็บได้ ใช้เป็นเป้าหมายของการปัด
SMALLEST_UNIT = Decimal(f"1E-{STORED_SCALE}")
