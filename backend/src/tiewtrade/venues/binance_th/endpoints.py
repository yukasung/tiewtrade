"""เส้นทางทั้งหมดที่ตัวเชื่อมนี้เรียกได้ — **รายการปิด** (F-07 RQ-16, `plan.md` ข้อ 6.4)

**ด่านค้นสตริงพิสูจน์ข้อนี้ไม่ได้** เส้นทางที่ประกอบจากตัวแปรจะผ่านด่านไปได้
ฉะนั้นชั้นที่บังคับจริงคือ **ชนิดข้อมูล**: ตัวส่งคำขอรับเฉพาะสมาชิกของ `Endpoint`
และสมาชิกที่ไม่ได้ประกาศไว้ที่นี่ **สร้างขึ้นมาไม่ได้เลย** ไม่ว่าจะต่อสตริงเก่งแค่ไหน

**นี่คือสิ่งที่กันความเสียหายจริงเมื่อเราตรวจสิทธิ์ของ key ไม่ได้** (NC-16) —
ตลาดอาจยอมให้ key ถอนเงินโดยที่ผู้ใช้ปิดไม่ได้ แต่โค้ดของเราไปถึง endpoint นั้นไม่ได้

**การเพิ่มสมาชิกคือการแก้ไฟล์นี้** ซึ่งเห็นในรีวิวเสมอ และต้องผ่านด่านที่ห้าม
เส้นทางที่ย้ายเงินออกจากบัญชีผู้ใช้ (ถอน โอนระหว่างบัญชี จัดการบัญชีย่อย)
"""

from __future__ import annotations

from enum import Enum


class Endpoint(Enum):
    """เส้นทางที่เรียกได้ — **อ่านอย่างเดียวทั้งหมดในตอนนี้**"""

    #: รายการเทรดล่าสุดของคู่หนึ่ง (F-35) — สาธารณะ
    TRADES = "/trades"
    #: รายการคู่เทรดและข้อจำกัดของแต่ละคู่ (F-35) — สาธารณะ
    EXCHANGE_INFO = "/exchangeInfo"
    #: ข้อมูลบัญชีและยอดในกระเป๋า (F-07) — **ต้องลงลายเซ็น**
    ACCOUNT = "/accountV2"

    @property
    def path(self) -> str:
        """เส้นทางที่ต่อท้าย base URL"""
        return self.value

    @property
    def needs_signature(self) -> bool:
        """เส้นทางนี้ต้องลงลายเซ็นหรือไม่"""
        return self is Endpoint.ACCOUNT
